import test from 'node:test';
import assert from 'node:assert/strict';
import {mediaGroupUrl,parseMediaUrl,uploadManifest,generatedSize} from '../server/media-contract.mjs';
const base='https://www.premiereflow.com',id='a0000000-0000-4000-8000-000000000001';
test('application media paths have a fixed origin, group and bounded ordinal',()=>{
 const group=mediaGroupUrl(base,id,2);
 assert.deepEqual(parseMediaUrl(base,group,{group:true}),{groupId:id,count:2,ordinal:null,url:group});
 assert.equal(parseMediaUrl(base,group+'nth/1/').ordinal,1);
 for(const u of [group+'nth/2/',group+'?owner=x',group+'nth/0/?token=x',group.replace('www.premiereflow.com','evil.example'),group.replace(id,'../a'),group+'nth/01/'])assert.throws(()=>parseMediaUrl(base,u));
 assert.throws(()=>parseMediaUrl(base,group+'nth/0/',{group:true}));
});
test('source upload budget includes originals and engine previews; unsupported/malicious manifests fail',()=>{
 const good={requestId:id,kind:'source',files:[{name:'..\\photo.jpg',mime:'image/jpeg',bytes:1000,previewBytes:500}]};
 const m=uploadManifest(good);assert.equal(m.totalBytes,1500);assert.equal(m.files[0].name,'.._photo.jpg');
 for(const bad of [{...good,accountId:'OTHER'},{...good,files:[]},{...good,files:Array(11).fill(good.files[0])},{...good,files:[{...good.files[0],mime:'image/svg+xml'}]},{...good,files:[{...good.files[0],bytes:30000001}]},{...good,files:[{...good.files[0],previewBytes:0}]}])assert.throws(()=>uploadManifest(bad));
});
test('generated byte count is exact for every base64 padding case and refuses oversized files',()=>{
 for(let n=1;n<=100;n++){const b=Buffer.alloc(n).toString('base64');assert.equal(generatedSize(b.length,b.slice(-4)),n);}
 for(const [n,tail] of [[0,'AAAA'],[5,'AAAA'],[4,'A==='],[40000004,'AAAA'],[4,'<x/>']])assert.throws(()=>generatedSize(n,tail));
});
